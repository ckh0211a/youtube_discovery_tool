def normalize_cookies_content(content):
    if not content:
        return ""
    if content.startswith('\ufeff'):
        content = content[1:]
    elif content.startswith('\xef\xbb\xbf'):
        content = content[3:]
    content = content.replace('\\n', '\n').replace('\r\n', '\n').strip()
    
    lines = []
    has_header = False
    for line in content.splitlines():
        line_str = line.strip()
        if not line_str:
            continue
        if line_str.startswith('#'):
            if 'Netscape HTTP Cookie File' in line_str:
                has_header = True
            lines.append(line_str)
            continue
        
        if '\t' in line:
            lines.append(line)
        else:
            parts = line_str.split(None, 6)
            if len(parts) == 7:
                lines.append('\t'.join(parts))
            elif len(parts) == 6:
                lines.append('\t'.join(parts) + '\t')
            else:
                lines.append(line)
                
    result = '\n'.join(lines) + '\n'
    if not has_header:
        result = "# Netscape HTTP Cookie File\n# http://curl.haxx.se/rfc/cookie_spec.html\n# This file was generated by yt-dlp! Edit at your own risk.\n\n" + result
    return result

